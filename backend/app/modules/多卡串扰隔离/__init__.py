"""多卡串扰隔离·独立主链路(架构甲:跨卡出站旁路,全局只贯彻甲)。

口径(硬推理约束:卡隔离是数据关系硬约束——成对双方卡号必须相等):
- 出站匹配开腿只查本卡在途腿,候选永不越卡;并发装载每卡独立在途栈,不串栈。
- 卡A在途时灌卡B出站:B无本卡开腿而他卡在途 → 判「跨卡无开腿」,B出站同票进
  旁路匣,A开腿仍在途;批内其他合法事件继续装载,批命运=继续(甲·旁路为准,
  不采用乙·拒整批)。
- 行程写闸:写行程账前断言开腿卡号==出站卡号,不等即拒写、同票旁路并记
  valid=0(失败闭可核);写后读回双端刷卡复核。
- 只读接口「隔离视图」逐笔给出:出站卡、候选开腿卡、批命运、旁路或回滚证据、valid。
"""

import json

from app.db import 连接
from app.seed import 此刻
from app.services import 时间, 配对

NAME = "多卡串扰隔离"

隔离架构 = "甲·跨卡出站旁路"
口径 = (
    "出站只匹配本卡在途开腿;出站卡无本卡开腿而他卡在途 → 跨卡无开腿同票旁路,"
    "他卡开腿仍在途,批命运=继续;行程写闸断言两端卡号相等,跨卡不得成对。"
)

建隔离表 = """
CREATE TABLE IF NOT EXISTS 多卡隔离 (
  编号 INTEGER PRIMARY KEY AUTOINCREMENT,
  批次编号 TEXT NOT NULL,
  出站事件编号 TEXT NOT NULL,
  出站卡 TEXT NOT NULL,
  候选开腿卡 TEXT NOT NULL DEFAULT '',
  批命运 TEXT NOT NULL,
  证据 TEXT NOT NULL DEFAULT '',
  valid INTEGER NOT NULL DEFAULT 1,
  时刻 TEXT NOT NULL
);
"""


def 确保隔离库() -> None:
    """建隔离判定表并登记全局架构(幂等;装载/贯验/页面共用)。"""
    conn = 连接()
    try:
        conn.executescript(建隔离表)
        conn.execute(
            "INSERT OR IGNORE INTO 站规(键, 值) VALUES ('多卡隔离架构', ?)",
            (隔离架构,),
        )
        conn.commit()
    finally:
        conn.close()


def 查在途开腿(conn, 卡号: str):
    """开腿查询:只查本卡在途腿——卡隔离硬约束落在查询层,候选永不越卡。"""
    return conn.execute(
        "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途' ORDER BY 进站事件时 ASC LIMIT 1",
        (卡号,),
    ).fetchone()


def _记隔离(conn, 批次编号, 出站事件编号, 出站卡, 候选开腿卡, 批命运, 证据, valid, 时刻):
    cur = conn.execute(
        """INSERT INTO 多卡隔离(批次编号,出站事件编号,出站卡,候选开腿卡,批命运,证据,valid,时刻)
           VALUES (?,?,?,?,?,?,?,?)""",
        (批次编号, 出站事件编号, 出站卡, 候选开腿卡, 批命运, 证据, valid, 时刻),
    )
    return cur.lastrowid


def _旁路(conn, 原因, 卡号, 事件编号, 载荷, 时刻):
    cur = conn.execute(
        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
        (原因, 卡号, 事件编号, json.dumps(载荷, ensure_ascii=False), 时刻),
    )
    return cur.lastrowid


def 成对写闸(conn, 开腿, 出站卡号, 出站事件编号, 出站站点键, 出站事件时, 处理时, 批次编号):
    """行程写闸:写行程账前断言两端卡号相等;不等即拒写+同票旁路+valid=0(可核)。

    返回行程键;被写闸拦截返回 None。正常路径候选来自查在途开腿(本卡),
    拦截分支是并发/误用下的纵深防线。
    """
    if 开腿["卡号"] != 出站卡号:
        旁路编号 = _旁路(
            conn,
            "跨卡写闸拦截",
            出站卡号,
            出站事件编号,
            {
                "开腿键": 开腿["开腿键"],
                "开腿卡": 开腿["卡号"],
                "出站卡": 出站卡号,
                "出站事件编号": 出站事件编号,
            },
            处理时,
        )
        conn.execute(
            "UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?", (出站事件编号,)
        )
        _记隔离(
            conn, 批次编号, 出站事件编号, 出站卡号, 开腿["卡号"], "继续",
            f"旁路编号:{旁路编号}·写闸拦截:开腿卡{开腿['卡号']}≠出站卡{出站卡号}",
            0, 处理时,
        )
        return None
    行程键 = 配对.成对写出站(conn, 开腿, 出站事件编号, 出站站点键, 出站事件时, 处理时)
    # 写后核:读回双端刷卡,两端卡号必须都等于行程卡号(跨卡不得成对)
    双端 = {
        r["事件编号"]: r["卡号"]
        for r in conn.execute(
            "SELECT 事件编号, 卡号 FROM 刷卡点 WHERE 行程键=?", (行程键,)
        )
    }
    if 双端.get(开腿["进站事件编号"]) != 出站卡号 or 双端.get(出站事件编号) != 出站卡号:
        raise RuntimeError(f"行程写闸写后核失败:{行程键}两端卡号不一致")
    _记隔离(
        conn, 批次编号, 出站事件编号, 出站卡号, 开腿["卡号"], "继续",
        f"行程键:{行程键}·两端卡号={出站卡号}", 1, 处理时,
    )
    return 行程键


def 装隔离批(体: dict) -> dict:
    """多卡隔离装载主链路:与成对 happy path 同形,但出站匹配强制本卡隔离。

    甲口径下批命运恒为「继续」:跨卡出站同票旁路,不回滚、不殃及批内他卡。
    """
    确保隔离库()
    批次编号 = 体.get("批次编号") or f"批-隔离-{此刻().replace(':', '').replace('-', '')}"
    事件列表 = 体.get("事件") or []
    conn = 连接()
    try:
        报告 = {
            "批次编号": 批次编号,
            "架构": 隔离架构,
            "批命运": "继续",
            "入流": 0,
            "开腿": 0,
            "成对": 0,
            "旁路": 0,
            "跨卡隔离": 0,
            "超时旁路": 0,
            "明细": [],
        }
        站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
        最大行程秒 = int(站.get("最大行程秒", "7200"))
        水位 = None

        for ev in 事件列表:
            事件编号 = ev["事件编号"]
            卡号 = ev["卡号"]
            站点键 = ev["站点键"]
            方向 = ev["方向"]
            事件时 = ev["事件时"]
            处理时 = ev.get("处理时") or 此刻()

            if 水位 is None or 时间.解析(事件时) > 时间.解析(水位):
                水位 = 事件时

            if conn.execute("SELECT 1 FROM 刷卡点 WHERE 事件编号=?", (事件编号,)).fetchone():
                报告["明细"].append({"事件编号": 事件编号, "命运": "幂等跳过"})
                continue

            站行 = conn.execute("SELECT * FROM 站点 WHERE 站点键=?", (站点键,)).fetchone()
            if not 站行:
                _旁路(conn, "未知站点", 卡号, 事件编号, ev, 处理时)
                conn.execute(
                    """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                       VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                    (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                )
                报告["旁路"] += 1
                报告["入流"] += 1
                报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-未知站"})
                continue

            if 方向 not in ("进站", "出站"):
                _旁路(conn, "方向非法", 卡号, 事件编号, ev, 处理时)
                conn.execute(
                    """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                       VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                    (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                )
                报告["旁路"] += 1
                报告["入流"] += 1
                报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-方向非法"})
                continue

            conn.execute(
                """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                   VALUES (?,?,?,?,?,?, '已入流', '', ?)""",
                (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
            )
            报告["入流"] += 1

            if 方向 == "进站":
                旧 = 查在途开腿(conn, 卡号)
                if 旧:
                    conn.execute(
                        "UPDATE 开腿账 SET 状态='已旁路', 更新处理时=? WHERE 开腿键=?",
                        (处理时, 旧["开腿键"]),
                    )
                    conn.execute(
                        "UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?",
                        (旧["进站事件编号"],),
                    )
                    _旁路(
                        conn, "重复进站", 卡号, 旧["进站事件编号"],
                        {"旧开腿": 旧["开腿键"], "新进站": 事件编号}, 处理时,
                    )
                    报告["旁路"] += 1
                    报告["明细"].append(
                        {"事件编号": 旧["进站事件编号"], "命运": "旁路-重复进站"}
                    )

                开腿键 = f"腿-{事件编号}"
                conn.execute(
                    """INSERT INTO 开腿账(开腿键,卡号,进站事件编号,进站站点键,进站事件时,状态,更新处理时)
                       VALUES (?,?,?,?,?,'在途',?)""",
                    (开腿键, 卡号, 事件编号, 站点键, 事件时, 处理时),
                )
                conn.execute(
                    "UPDATE 刷卡点 SET 命运='已开腿' WHERE 事件编号=?", (事件编号,)
                )
                报告["开腿"] += 1
                报告["明细"].append({"事件编号": 事件编号, "命运": "已开腿", "开腿键": 开腿键})
            else:
                开腿 = 查在途开腿(conn, 卡号)
                if 开腿:
                    行程键 = 成对写闸(
                        conn, 开腿, 卡号, 事件编号, 站点键, 事件时, 处理时, 批次编号
                    )
                    if 行程键:
                        报告["成对"] += 1
                        报告["明细"].append(
                            {"事件编号": 事件编号, "命运": "已成对", "行程键": 行程键}
                        )
                    else:
                        报告["旁路"] += 1
                        报告["跨卡隔离"] += 1
                        报告["明细"].append(
                            {"事件编号": 事件编号, "命运": "旁路-跨卡写闸拦截"}
                        )
                    continue

                # 本卡无在途开腿:看候选是否越卡(他卡在途 → 跨卡串扰未遂)
                候选 = conn.execute(
                    "SELECT * FROM 开腿账 WHERE 状态='在途' ORDER BY 进站事件时 ASC LIMIT 1"
                ).fetchone()
                if 候选:
                    旁路编号 = _旁路(
                        conn, "跨卡无开腿", 卡号, 事件编号,
                        {
                            "出站事件": ev,
                            "候选开腿键": 候选["开腿键"],
                            "候选开腿卡": 候选["卡号"],
                            "处置": "同票旁路·候选开腿仍在途(架构甲)",
                        },
                        处理时,
                    )
                    conn.execute(
                        "UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?", (事件编号,)
                    )
                    _记隔离(
                        conn, 批次编号, 事件编号, 卡号, 候选["卡号"], "继续",
                        f"旁路编号:{旁路编号}·原因:跨卡无开腿·候选开腿{候选['开腿键']}仍在途",
                        1, 处理时,
                    )
                    报告["旁路"] += 1
                    报告["跨卡隔离"] += 1
                    报告["明细"].append(
                        {
                            "事件编号": 事件编号,
                            "命运": "旁路-跨卡无开腿",
                            "候选开腿卡": 候选["卡号"],
                        }
                    )
                else:
                    旁路编号 = _旁路(conn, "出站孤儿", 卡号, 事件编号, ev, 处理时)
                    conn.execute(
                        "UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?", (事件编号,)
                    )
                    _记隔离(
                        conn, 批次编号, 事件编号, 卡号, "", "继续",
                        f"旁路编号:{旁路编号}·原因:出站孤儿·全库无在途开腿",
                        1, 处理时,
                    )
                    报告["旁路"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-出站孤儿"})

        if 水位:
            报告["超时旁路"] = 配对.扫缺腿超时(conn, 最大行程秒, 水位, 此刻())
            报告["旁路"] += 报告["超时旁路"]

        conn.execute(
            "INSERT INTO 装载批次(编号, 时刻, 报告) VALUES (?,?,?)",
            (批次编号, 此刻(), json.dumps(报告, ensure_ascii=False)),
        )
        conn.commit()
        return 报告
    finally:
        conn.close()


def 隔离视图(批命运: str = "", 批次编号: str = "") -> list:
    """多卡隔离只读接口:出站卡、候选开腿卡、批命运、旁路或回滚证据、valid。"""
    确保隔离库()
    conn = 连接()
    try:
        sql = (
            "SELECT 编号, 批次编号, 出站事件编号, 出站卡, 候选开腿卡, 批命运, 证据, valid, 时刻"
            " FROM 多卡隔离"
        )
        条件, 参 = [], []
        if 批命运:
            条件.append("批命运=?")
            参.append(批命运)
        if 批次编号:
            条件.append("批次编号=?")
            参.append(批次编号)
        if 条件:
            sql += " WHERE " + " AND ".join(条件)
        sql += " ORDER BY 编号 DESC LIMIT 200"
        行 = []
        for r in conn.execute(sql, 参):
            d = dict(r)
            d["valid"] = bool(d["valid"])
            行.append(d)
        return 行
    finally:
        conn.close()
